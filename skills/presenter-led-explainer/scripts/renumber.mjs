#!/usr/bin/env node
/* Number the slides by their position in deck.json: s01, s02, ... so the scenes/ listing is the play order
   (the intro and outro included: an intro after the hook is s02, the outro is the last number).
   Why: ids that sort in play order make the folder readable; reorder slides in deck.json, run this, then build.
   Renames scenes/<old>.html (and .png), rewrites the ids in deck.json, the "Scen:" tags in script.md and slide references in scene scripts.
   Run: node renumber.mjs [videos/001-slug] */
import { existsSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { videoDir } from './lib.mjs';

const dir = videoDir(process.argv[2]);
const deckFile = join(dir, 'deck.json'), deck = JSON.parse(readFileSync(deckFile, 'utf8'));
const width = Math.max(2, String(deck.slides.length).length);
const map = new Map(deck.slides.map((s, i) => [s.id, `s${String(i + 1).padStart(width, '0')}`]));
const changes = [...map].filter(([a, b]) => a !== b);
if (!changes.length) { console.log('ids already match the slide order'); process.exit(0); }

// 1. files: via temporary names so ids can swap places
const ext = ['html', 'png'], tmp = id => join(dir, 'scenes', `~${id}`);
for (const [a] of changes) for (const e of ext) if (existsSync(`${join(dir, 'scenes', a)}.${e}`)) renameSync(`${join(dir, 'scenes', a)}.${e}`, `${tmp(a)}.${e}`);
for (const [a, b] of changes) for (const e of ext) if (existsSync(`${tmp(a)}.${e}`)) renameSync(`${tmp(a)}.${e}`, `${join(dir, 'scenes', b)}.${e}`);

// 2. references: deck.json, <title> numbers and slide ids in the scene scripts, "Scen:" tags in script.md
deck.slides.forEach(s => { s.id = map.get(s.id); });
writeFileSync(deckFile, JSON.stringify(deck, null, 2) + '\n');
const sub = text => text.replace(/\b[sS]\d{2,}\b|\b(?:intro|outro)\b/g, m => { const n = map.get(m.toLowerCase()); return n ? (m[0] === 'S' ? n.toUpperCase() : n) : m; });
for (const s of deck.slides) {
  const f = join(dir, 'scenes', `${s.id}.html`); if (s.template || !existsSync(f)) continue;   // template scenes are regenerated by build
  const n = s.id.slice(1);
  writeFileSync(f, readFileSync(f, 'utf8').replace(/<script>[\s\S]*?<\/script>/g, b => b.replace(/\b[sS]\d{2,}\b/g, m => map.get(m.toLowerCase()) ?? m)).replace(/<title>\d+ /, `<title>${n} `));
}
const sf = join(dir, 'script.md');
if (existsSync(sf)) writeFileSync(sf, readFileSync(sf, 'utf8').replace(/(\*\*Scen:\*\* )(\w+)/g, (_, p, id) => p + (/^s\d+$/i.test(id) ? sub(id) : map.get(id) ? map.get(id).toUpperCase() : id)));
console.log(changes.map(([a, b]) => `${a} -> ${b}`).join('\n') + '\nNow run: build.mjs (regenerates the intro/outro pages and index.html)');
